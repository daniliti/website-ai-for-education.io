def render_block(doc, block):
    t = block["t"]
    if t == "h2":
        add_h2(doc, clean(block["x"]))
    elif t == "p":
        add_p(doc, clean(block["x"]))
    elif t == "lead":
        add_lead(doc, clean(block["x"]))
    elif t == "list":
        add_bullets(doc, [clean(x) for x in block["items"]])
    elif t == "num":
        add_numbered(doc, [clean(x) for x in block["items"]])
    elif t == "callout":
        add_callout(doc, clean(block["title"]), clean(block["x"]), block.get("tone", "info"))
    elif t == "table":
        add_table(doc, [clean(x) for x in block["head"]], [[clean(c) for c in row] for row in block["rows"]])
    elif t == "comparison":
        add_table(doc, ["Слабый вариант", "Рабочий вариант"], [[clean(block["left"]), clean(block["right"])]], widths=(8.3, 8.3))
        if block.get("caption"):
            add_p(doc, clean(block["caption"]), size=9, italic=True, color=MUTED)
    elif t == "steps":
        add_numbered(doc, [f"{clean(a)}. {clean(b)}" for a, b in block["items"]])
    elif t == "scenarios":
        rows = [[clean(s["title"]), clean(s["text"]), clean(s["answer"])] for s in block["items"]]
        add_table(doc, ["Ситуация", "Что произошло", "Ориентир для разбора"], rows, widths=(3.5, 7.0, 6.1), font_size=8.2)
    elif t == "checklist":
        add_bullets(doc, ["□ " + clean(x) for x in CHECKLISTS[block["id"]]], size=9.8)
    elif t == "rubric_preview":
        add_table(doc, ["Критерий", "Проверочный вопрос"], [[clean(a), clean(b)] for a, b in block["items"]], widths=(5.5, 11.1))
    elif t in ("practice", "quiz", "artifact", "project_cta"):
        pass
    else:
        add_p(doc, clean(block.get("x", "")), size=9, color=MUTED)


def add_practice(doc, p):
    add_h3(doc, clean(p["title"]))
    add_p(doc, clean(p.get("intro", "")), size=10)
    if p.get("prompt"):
        add_prompt_box(doc, clean(p["prompt"]))
    if p.get("steps"):
        add_bullets(doc, [clean(s) for s in p["steps"]], size=9.8)
    if p.get("fields"):
        add_p(doc, "Что зафиксировать:", size=9.4, bold=True, color=FOREST)
        add_bullets(doc, [clean(f["label"]) for f in p["fields"]], size=9.6)
    if p.get("note"):
        add_p(doc, clean(p["note"]), size=9, italic=True, color=MUTED)


def add_quiz(doc, items):
    add_h2(doc, "Проверка понимания")
    add_p(doc, "Вопросы можно использовать для устного обсуждения, в чате или как короткую самопроверку. Ниже — ключ для ведущего.", size=9.5, color=MUTED)
    for i, item in enumerate(items, 1):
        add_p(doc, f"{i}. {clean(item['q'])}", size=10, bold=True)
        letters = ["А", "Б", "В", "Г", "Д", "Е"]
        add_bullets(doc, [f"{letters[i]}) {clean(o)}" for i, o in enumerate(item["options"])], size=9.4)
    add_h3(doc, "Ключ и комментарии")
    rows = []
    for i, item in enumerate(items, 1):
        rows.append([str(i), clean(item["options"][item["correct"]]), clean(item["explain"])])
    add_table(doc, ["№", "Верный ответ", "Почему"], rows, widths=(1.0, 6.6, 9.0), font_size=8.4)


def add_module(doc, m):
    n = m["n"]
    add_h1(doc, f"Модуль {n:02d}. {m['title']}")
    add_lead(doc, clean(m["lede"]))
    add_meta_table(doc, [
        ("Время", f"{hours_label(m['hours'])} · {m['minutes']} минут"),
        ("Результат", clean(m["result"])),
        ("Формат", "Объяснение, демонстрация, индивидуальная и парная работа, обсуждение"),
        ("Материалы", NOTES[n]["materials"]),
    ])
    add_h2(doc, "Цели модуля")
    add_p(doc, "Участники:", size=9.5, color=MUTED)
    add_bullets(doc, [clean(x) for x in m["goals"]])

    add_h2(doc, "План и тайминг")
    add_table(doc, ["Время", "Этап"], [[t, clean(d)] for t, d in m["timing"]], widths=(2.2, 14.4), font_size=8.8)

    add_h2(doc, "Ключевые положения")
    for block in m["blocks"]:
        render_block(doc, block)

    practices = [b for b in m["blocks"] if b["t"] == "practice"]
    if practices:
        add_h2(doc, "Практика")
        for p in practices:
            add_practice(doc, p)

    quiz = next((b for b in m["blocks"] if b["t"] == "quiz"), None)
    if quiz:
        add_quiz(doc, quiz["items"])

    add_h2(doc, "Комментарии ведущему")
    add_callout(doc, "Главная мысль модуля", NOTES[n]["key"], "info")
    add_h3(doc, "Типичные трудности")
    add_bullets(doc, NOTES[n]["difficulties"], size=9.8)
    add_h3(doc, "Дифференциация")
    add_bullets(doc, NOTES[n]["differentiation"], size=9.8)
    add_h3(doc, "Если нет доступа к сервису")
    add_p(doc, NOTES[n]["offline"], size=9.8)
    add_h3(doc, "Вопросы для обсуждения")
    add_bullets(doc, NOTES[n]["debrief"], size=9.8)

    art = next((b for b in m["blocks"] if b["t"] == "artifact"), None)
    if art:
        add_callout(doc, "Результат модуля", clean(art["x"]), "good")
        add_bullets(doc, ["□ " + clean(x) for x in art.get("items", [])], size=9.6)
    add_p(doc, "Межмодульная работа: 20–30 минут на доработку артефакта перед следующей встречей. Если курс идёт асинхронно, этот шаг входит в часы модуля.", size=8.8, italic=True, color=MUTED)


